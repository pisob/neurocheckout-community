import { chmodSync, existsSync, writeFileSync } from "node:fs";
import { randomBytes } from "node:crypto";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { createInterface } from "node:readline/promises";

import {
  formatEnvironmentValue,
  readEnvironmentFile,
} from "./env-file.mjs";

const DEFAULTS = {
  redirectUri: "http://localhost:3400/api/auth/callback",
  cloudApiBaseUrl: "https://www.neurocheckout.com",
  cloudAuthorizationUrl: "https://www.neurocheckout.com/community/authorize",
  cloudUpgradeUrl: "https://www.neurocheckout.com/pricing",
};

export function isPlaceholder(value) {
  const normalized = String(value || "").trim().toLowerCase();
  return (
    !normalized ||
    normalized.includes("replace_with") ||
    normalized.includes("replace-with") ||
    normalized.includes("replace_me") ||
    normalized.includes("replace-me") ||
    normalized.includes("change_me") ||
    normalized.includes("change-me")
  );
}

export function isLoopbackHostname(hostname) {
  return ["localhost", "127.0.0.1", "::1", "[::1]"].includes(
    String(hostname).toLowerCase(),
  );
}

export function validateClientId(value) {
  const clientId = String(value || "").trim();
  if (isPlaceholder(clientId) || clientId.length < 8 || /\s/.test(clientId)) {
    throw new Error("Enter the public client ID created by NeuroCheckout Cloud.");
  }
  return clientId;
}

export function validateRedirectUri(value) {
  let url;
  try {
    url = new URL(String(value || "").trim());
  } catch {
    throw new Error("The callback URL is not a valid absolute URL.");
  }

  const loopback = isLoopbackHostname(url.hostname);
  if (url.protocol !== "https:" && !(url.protocol === "http:" && loopback)) {
    throw new Error("Use HTTPS, except for an HTTP callback on localhost.");
  }
  if (url.pathname !== "/api/auth/callback" || url.search || url.hash) {
    throw new Error("The callback must end exactly with /api/auth/callback.");
  }
  if (url.username || url.password) {
    throw new Error("The callback URL cannot contain credentials.");
  }
  return url.toString();
}

export function createSessionSecret() {
  return randomBytes(48).toString("base64url");
}

export function renderConfiguration(values) {
  const entries = [
    ["NC_COMMUNITY_CLIENT_ID", values.clientId],
    ["NC_COMMUNITY_REDIRECT_URI", values.redirectUri],
    ["NC_CLOUD_API_BASE_URL", values.cloudApiBaseUrl],
    ["NC_CLOUD_AUTHORIZATION_URL", values.cloudAuthorizationUrl],
    ["NC_CLOUD_UPGRADE_URL", values.cloudUpgradeUrl],
    ["NC_COMMUNITY_SESSION_SECRET", values.sessionSecret],
    ["NC_COMMUNITY_COOKIE_SECURE", String(values.cookieSecure)],
  ];

  return [
    "# Generated by npm run setup. Never commit this file.",
    ...entries.map(
      ([name, value]) => `${name}=${formatEnvironmentValue(value)}`,
    ),
    "",
  ].join("\n");
}

function parseArguments(argv) {
  const options = { output: ".env.local", force: false };
  for (const argument of argv) {
    if (argument === "--force") options.force = true;
    else if (argument.startsWith("--client-id=")) {
      options.clientId = argument.slice("--client-id=".length);
    } else if (argument.startsWith("--redirect-uri=")) {
      options.redirectUri = argument.slice("--redirect-uri=".length);
    } else if (argument.startsWith("--output=")) {
      options.output = argument.slice("--output=".length);
    } else {
      throw new Error(`Unknown option: ${argument}`);
    }
  }
  return options;
}

async function promptForValue(reader, label, current = "") {
  const suffix = current ? ` [${current}]` : "";
  const answer = (await reader.question(`${label}${suffix}: `)).trim();
  return answer || current;
}

export async function main(argv = process.argv.slice(2)) {
  const major = Number(process.versions.node.split(".")[0]);
  if (major < 22) throw new Error("Node.js 22 or newer is required.");

  const options = parseArguments(argv);
  const output = resolve(options.output);
  const existing = readEnvironmentFile(output);
  const interactive = Boolean(process.stdin.isTTY && process.stdout.isTTY);
  const reader = interactive
    ? createInterface({ input: process.stdin, output: process.stdout })
    : null;

  try {
    const currentClientId = isPlaceholder(existing.NC_COMMUNITY_CLIENT_ID)
      ? ""
      : existing.NC_COMMUNITY_CLIENT_ID || "";
    const currentRedirect =
      existing.NC_COMMUNITY_REDIRECT_URI || DEFAULTS.redirectUri;

    const rawClientId =
      options.clientId ||
      (reader
        ? await promptForValue(reader, "Public Cloud client ID", currentClientId)
        : currentClientId);
    const rawRedirect =
      options.redirectUri ||
      (reader
        ? await promptForValue(reader, "Exact callback URL", currentRedirect)
        : currentRedirect);

    const clientId = validateClientId(rawClientId);
    const redirectUri = validateRedirectUri(rawRedirect);
    const sessionSecret =
      !isPlaceholder(existing.NC_COMMUNITY_SESSION_SECRET) &&
      String(existing.NC_COMMUNITY_SESSION_SECRET).length >= 32
        ? existing.NC_COMMUNITY_SESSION_SECRET
        : createSessionSecret();

    if (existsSync(output) && !options.force && !reader) {
      throw new Error(`Refusing to overwrite ${options.output} without --force.`);
    }
    if (existsSync(output) && !options.force && reader) {
      const confirmation = (
        await reader.question(`Update ${options.output}? [Y/n]: `)
      )
        .trim()
        .toLowerCase();
      if (confirmation && confirmation !== "y" && confirmation !== "yes") {
        console.log("Configuration unchanged.");
        return;
      }
    }

    const configuration = renderConfiguration({
      clientId,
      redirectUri,
      cloudApiBaseUrl:
        existing.NC_CLOUD_API_BASE_URL || DEFAULTS.cloudApiBaseUrl,
      cloudAuthorizationUrl:
        existing.NC_CLOUD_AUTHORIZATION_URL || DEFAULTS.cloudAuthorizationUrl,
      cloudUpgradeUrl:
        existing.NC_CLOUD_UPGRADE_URL || DEFAULTS.cloudUpgradeUrl,
      sessionSecret,
      cookieSecure: new URL(redirectUri).protocol === "https:",
    });

    writeFileSync(output, configuration, { encoding: "utf8", mode: 0o600 });
    chmodSync(output, 0o600);
    console.log(`Configuration saved securely to ${options.output}.`);
    console.log(`Registered callback: ${redirectUri}`);
    console.log("The generated session secret was not displayed.");
  } finally {
    reader?.close();
  }
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  main().catch((error) => {
    console.error(`Setup failed: ${error.message}`);
    process.exitCode = 1;
  });
}
